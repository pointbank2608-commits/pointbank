import assert from 'node:assert/strict';
import { buildAdaptiveFixture } from './adaptive-homework-fixture.mjs';

const f = await buildAdaptiveFixture();
const silentStudent = crypto.randomUUID();
const cards = JSON.stringify([{ word: 'bank', meaning: '은행' }, { word: 'bank', meaning: '둑' }]);
const teacher = (academy = f.A) => f.db.exec(`reset role; set role authenticated;
  select set_config('test.staff','yes',false),set_config('test.academy','${academy}',false)`);
const student = () => f.db.exec('reset role; set role anon');
const feedback = lesson => f.call('learning_vocab_feedback', f.HW, lesson);
const approve = (id, title, selectedCards, draft = null) =>
  f.call('learning_vocab_approve', id, f.HW, draft ? [f.ST] : [f.ST, silentStudent], title, selectedCards, 'letters', true, draft, null);
const studentRows = async lesson => (await feedback(lesson)).rows.filter(row => row.student_id === f.ST);
const assignment = async lesson =>
  (await f.one('select id from solo_assignments where lesson_id=$1 and student_id=$2', [lesson, f.ST])).id;
const act = (id, position, action, value = null, request = crypto.randomUUID()) =>
  f.call('learning_path_action', f.TK, id, request, position, action, value);

try {
  await f.db.exec(f.read('115_vocab_learning_loop.sql'));
  await f.db.exec(f.read('115_vocab_learning_loop.sql'));
  const compat = (await f.db.query(f.read('099_check.sql'))).rows[0];
  assert.ok(Object.values(compat).every(Boolean), 'legacy wrappers remain compatible');
  assert.ok(Object.values((await f.db.query(f.read('115_check.sql'))).rows[0]).every(Boolean));
  await f.db.query("insert into students(id,academy_id,class_id,name) values($1,$2,$3,'미응답 학생')", [silentStudent, f.A, f.HW]);
  await teacher();
  const initialId = crypto.randomUUID();
  const plan = await approve(initialId, 'Vocabulary lesson', cards);
  assert.equal((await approve(initialId, 'Vocabulary lesson', cards)).duplicate, true);
  await assert.rejects(() => approve(initialId, 'Changed retry', cards), /request_changed/);
  await assert.rejects(() => f.db.query('select * from learning_vocab_drafts'), /permission denied/);
  assert.equal(await f.call('learning_vocab_draft', plan.lesson_id, 'homework', null), null, 'unanswered items do not generate a recommendation');
  assert.ok((await feedback(plan.lesson_id)).rows.every(row => row.independent_correct === null && row.homework_id === null));

  await f.db.exec('reset role');
  const solo = await assignment(plan.lesson_id);
  await student();
  await assert.rejects(() => feedback(plan.lesson_id), /permission denied/);
  await assert.rejects(() => f.call('learning_path_open', f.otherToken, solo), /not_found/);
  const initial = await f.call('learning_path_open', f.TK, solo);
  assert.equal(initial.step.word, undefined);
  assert.equal(initial.step.game_choices, undefined);
  const learned = await act(solo, 1, 'unknown');
  assert.equal(learned.state.step.vocab_game, 'meaning-balloon-v1');
  assert.equal(new Set(learned.state.step.game_choices).size, 3);
  await assert.rejects(() => act(solo, 2, 'continue'), /bad_game_choice/);
  const wrong = learned.state.step.game_choices.find(word => word !== 'bank');
  const shot = crypto.randomUUID();
  const miss = await act(solo, 2, 'continue', wrong, shot);
  assert.equal(miss.game_correct, false);
  assert.equal(miss.state.position, 2);
  assert.deepEqual(await act(solo, 2, 'continue', wrong, shot), miss);
  assert.equal((await act(solo, 2, 'continue', 'bank')).state.step.vocab_game, 'spelling-train-v1');
  await act(solo, 3, 'hint');
  assert.equal((await act(solo, 3, 'answer', 'bank')).feedback.correct, true);
  assert.equal((await act(solo, 4, 'unknown')).state.phase, 'learn');
  await act(solo, 2, 'continue', 'bank');
  await act(solo, 3, 'answer', 'bank');
  await act(solo, 4, 'unknown');
  assert.equal((await act(solo, 5, 'answer', 'bank')).state.phase, 'check', 'known word bypasses practice games');
  await act(solo, 8, 'answer', 'bank');
  await f.call('learning_path_open', f.TK, solo); // A new run must not erase earlier evidence.
  await teacher();
  const [bank, riverbank] = await studentRows(plan.lesson_id);
  const unobserved = (await feedback(plan.lesson_id)).rows.filter(row => row.student_id === silentStudent);
  assert.equal(unobserved.length, 2);
  assert.ok(unobserved.every(row => row.first_correct === null && row.latest_correct === null));
  assert.deepEqual([bank.first_correct, bank.first_check_correct, bank.independent_correct, bank.practice_hint_used], [false, false, false, true]);
  assert.deepEqual([riverbank.first_correct, riverbank.independent_correct], [true, true]);
  const draft = await f.call('learning_vocab_draft', plan.lesson_id, 'homework', null);
  assert.equal(draft.reason, 'practice');
  assert.deepEqual(draft.students, [f.ST], 'class recommendations do not treat an unanswered item as a failure');
  assert.deepEqual(draft.cards.map(card => card.meaning), ['은행'], 'class draft starts with the goal that needs practice');
  assert.deepEqual((await feedback(plan.lesson_id)).drafts.map(row => row.id), [draft.id]);
  assert.ok((await feedback(plan.lesson_id)).rows.every(row => row.homework_id === null), 'draft creation never assigns');
  await teacher(f.B);
  await assert.rejects(() => feedback(plan.lesson_id), /bad_class/);
  await assert.rejects(() => f.call('learning_vocab_draft', plan.lesson_id, 'homework', null), /not_found/);
  await teacher();
  await assert.rejects(() => approve(draft.id, 'Edited follow-up', JSON.stringify([{ word: 'dog', meaning: '개' }]), draft.id), /bad_link_goal/);
  const edited = JSON.stringify([{ word: 'bank', meaning: '은행', example: 'I went to the bank.' }]);
  const homework = await approve(draft.id, 'Edited follow-up', edited, draft.id);
  assert.equal((await approve(draft.id, 'Edited follow-up', edited, draft.id)).duplicate, true);
  assert.equal((await feedback(plan.lesson_id)).followups[0].id, homework.lesson_id);
  const pending = await studentRows(plan.lesson_id);
  assert.equal(pending[0].homework_correct, null);
  assert.ok(pending[0].homework_id);
  assert.equal(pending[1].homework_id, null, 'identical spelling alone must not connect different meanings');
  const next = await f.call('learning_vocab_draft', plan.lesson_id, 'lesson', f.ST);
  assert.equal(next, null, 'an unanswered linked homework is not evidence for another intervention');
  await student();
  const hw = pending[0].homework_id;
  assert.equal((await f.call('student_home', f.TK)).lessons.find(item => item.id === hw).kind, 'homework');
  await f.call('learning_path_open', f.TK, hw);
  await act(hw, 1, 'answer', 'bank');
  await act(hw, 4, 'answer', 'bank');
  await f.call('learning_path_open', f.TK, hw);
  await teacher();
  const [after] = await studentRows(plan.lesson_id);
  assert.deepEqual([after.independent_correct, after.homework_correct, after.latest_correct], [false, true, true]);
  const verify = await f.call('learning_vocab_draft', plan.lesson_id, 'homework', f.ST);
  assert.equal(verify.reason, 'check');
  await f.call('learning_vocab_dismiss', verify.id);
  await assert.rejects(() => approve(verify.id, 'Skipped draft', cards, verify.id), /draft_not_available/);
  assert.deepEqual((await feedback(plan.lesson_id)).drafts, []);
  await f.db.exec('reset role');
  await f.db.query("update learning_path_states set due_at=now()-interval '1 hour' where assignment_id=$1", [hw]);
  await student();
  await act(hw, 4, 'unknown');
  await teacher();
  const repeat = await f.call('learning_vocab_draft', plan.lesson_id, 'lesson', f.ST);
  assert.equal(repeat.reason, 'practice');
  const nextLesson = await approve(repeat.id, 'Revised vocabulary lesson', edited, repeat.id);
  assert.ok((await feedback(plan.lesson_id)).followups.some(item => item.id === nextLesson.lesson_id && item.kind === 'lesson'));
  await f.db.exec('reset role');
  await f.db.exec(f.read('115_rollback.sql'));
  await teacher();
  await assert.rejects(() => feedback(plan.lesson_id), /permission denied/);
  await student();
  assert.equal((await f.call('learning_path_open', f.TK, solo)).phase, 'delayed_check');
  await f.db.exec('reset role');
  await f.db.exec(f.read('115_vocab_learning_loop.sql'));
  assert.ok(Object.values((await f.db.query(f.read('115_check.sql'))).rows[0]).every(Boolean));
  console.log('Vocabulary loop DB passed: frozen games, verified checks across runs, exact goals, draft approval/retry, scope and missing evidence.');
} catch (error) {
  console.error(error.message, error.detail ?? '', error.where ?? '');
  process.exitCode = 1;
} finally {
  await f.db.close();
}
