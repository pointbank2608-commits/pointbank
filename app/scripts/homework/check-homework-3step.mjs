 await composer().getByRole('checkbox',{name:'마무리 확인 추가'}).check();
 const all=['그림이나 뜻을 보고 단어 고르기','음성을 듣고 단어 고르기','빠진 알파벳 채우기','뜻을 보고 철자 직접 쓰기','알파벳을 배열해 단어 만들기','단어를 배열해 문장 만들기','문장 빈칸에 맞는 단어 고르기','단어·문장 혼자 말하기'];
